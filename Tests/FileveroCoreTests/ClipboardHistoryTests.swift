import XCTest

@testable import FileveroCore

final class ClipboardHistoryTests: XCTestCase {
    private func text(_ value: String) -> Data { Data(value.utf8) }

    private func entry(_ value: String, pinned: Bool = false, at seconds: TimeInterval = 0) -> ClipboardEntry {
        let formats: [ClipboardFormat: Data] = [.plainText: text(value)]
        return ClipboardEntry(
            id: UUID(), created: Date(timeIntervalSince1970: seconds), pinned: pinned, sourceApp: nil,
            kind: .text, preview: value, formats: [.plainText], digest: ClipboardHistory.digest(of: formats))
    }

    func testPasswordManagerMarkersAndExcludedAppsAreNeverRecorded() {
        let formats: [ClipboardFormat: Data] = [.plainText: text("secret")]
        for marker in [
            "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
            "app.filevero.clipboard-restore",
        ] {
            let capture = ClipboardCapture(formats: formats, sourceApp: "com.apple.TextEdit", markers: [marker])
            XCTAssertFalse(ClipboardHistory.shouldRecord(capture, excludedApps: []), marker)
        }
        let fromPasswordManager = ClipboardCapture(formats: formats, sourceApp: "com.bitwarden.desktop", markers: [])
        XCTAssertFalse(
            ClipboardHistory.shouldRecord(fromPasswordManager, excludedApps: Set(ClipboardHistory.defaultExcludedApps)))
        let ordinary = ClipboardCapture(formats: formats, sourceApp: "com.apple.TextEdit", markers: [])
        XCTAssertTrue(ClipboardHistory.shouldRecord(ordinary, excludedApps: Set(ClipboardHistory.defaultExcludedApps)))
    }

    func testExcelLikeCopyIsRichTextAndKeepsEveryFormat() throws {
        let formats: [ClipboardFormat: Data] = [
            .plainText: text("1\t2"), .html: text("<table/>"), .rtf: text("{\\rtf1}"), .png: Data(count: 64),
        ]
        XCTAssertEqual(ClipboardHistory.kind(of: formats), .richText)
        XCTAssertEqual(try XCTUnwrap(ClipboardHistory.fitted(formats)), formats)
    }

    func testFinderCopyIsAFileNotItsIcon() {
        let formats: [ClipboardFormat: Data] = [
            .fileURLs: text("/tmp/a.png"), .png: Data(count: 8), .plainText: text("a.png"),
        ]
        XCTAssertEqual(ClipboardHistory.kind(of: formats), .file)
    }

    func testImageOnlyCopyIsAnImage() {
        XCTAssertEqual(ClipboardHistory.kind(of: [.png: Data(count: 8)]), .image)
    }

    func testWholeURLTextIsALink() {
        XCTAssertEqual(ClipboardHistory.kind(of: [.plainText: text("https://filevero.app/x")]), .link)
        XCTAssertEqual(ClipboardHistory.kind(of: [.plainText: text("see https://a.b")]), .text)
        XCTAssertEqual(ClipboardHistory.kind(of: [.plainText: text("ftp://a")]), .text)
    }

    func testOversizedImageIsDroppedButTextKept() {
        let large = Data(count: 11 * 1_048_576)
        XCTAssertEqual(
            ClipboardHistory.fitted([.png: large, .plainText: text("0123456789")]), [.plainText: text("0123456789")])
        XCTAssertNil(ClipboardHistory.fitted([.png: large]))
    }

    func testDuplicateMovesToTopAndKeepsPin() throws {
        let first = entry("A", at: 1)
        let second = entry("B", at: 2)
        var history = ClipboardHistory(entries: [], bootTime: nil)
            .inserting(first, limit: 200)
            .inserting(second, limit: 200)
        history = history.togglingPin(first.id)
        let again = entry("A", at: 3)
        history = history.inserting(again, limit: 200)

        XCTAssertEqual(history.entries.count, 2)
        XCTAssertEqual(history.entries[0].id, first.id)
        XCTAssertTrue(history.entries[0].pinned)
        XCTAssertEqual(history.entries[0].created, again.created)
    }

    func testLimitNeverEvictsPinnedEntries() {
        let pinned = (0..<3).map { entry("pinned \($0)", pinned: true, at: TimeInterval($0)) }
        let older = entry("older", at: 10)
        let newer = entry("newer", at: 11)
        let history = ClipboardHistory(entries: [newer, older] + pinned, bootTime: nil)
        let latest = entry("latest", at: 12)

        let result = history.inserting(latest, limit: 2)

        XCTAssertEqual(Set(result.entries.filter(\.pinned).map(\.id)), Set(pinned.map(\.id)))
        XCTAssertEqual(result.entries.filter { !$0.pinned }.map(\.id), [latest.id, newer.id])
    }

    func testLoweringTheLimitTrimsOldestUnpinnedRightAway() {
        let pinned = entry("pinned", pinned: true, at: 1)
        let older = entry("older", at: 2)
        let newer = entry("newer", at: 3)
        let history = ClipboardHistory(entries: [newer, older, pinned], bootTime: nil)

        XCTAssertEqual(history.trimmed(toLimit: 1).entries.map(\.id), [newer.id, pinned.id])
        XCTAssertEqual(history.trimmed(toLimit: 5), history)
    }

    func testRestartClearsOnlyUnpinnedWhenEnabled() {
        let boot = Date(timeIntervalSince1970: 1_000)
        let later = Date(timeIntervalSince1970: 2_000)
        let kept = entry("kept", pinned: true)
        let history = ClipboardHistory(entries: [entry("gone"), kept], bootTime: boot)

        let cleared = history.afterBoot(later, clearOnRestart: true)
        XCTAssertEqual(cleared.entries.map(\.id), [kept.id])
        XCTAssertEqual(cleared.bootTime, later)

        let disabled = history.afterBoot(later, clearOnRestart: false)
        XCTAssertEqual(disabled.entries.count, 2)
        XCTAssertEqual(disabled.bootTime, later)

        XCTAssertEqual(history.afterBoot(boot, clearOnRestart: true).entries.count, 2)
    }

    func testDigestIsOrderIndependentAndContentSensitive() {
        let a: [ClipboardFormat: Data] = [.plainText: text("x"), .html: text("<b>x</b>")]
        let b: [ClipboardFormat: Data] = [.html: text("<b>x</b>"), .plainText: text("x")]
        XCTAssertEqual(ClipboardHistory.digest(of: a), ClipboardHistory.digest(of: b))
        XCTAssertNotEqual(ClipboardHistory.digest(of: a), ClipboardHistory.digest(of: [.plainText: text("x")]))
        XCTAssertNotEqual(ClipboardHistory.digest(of: [.plainText: text("x")]), ClipboardHistory.digest(of: [.html: text("x")]))
    }

    func testShortcutStorageFallsBackToDefaultAndOnlyShiftWarns() {
        XCTAssertEqual(ClipboardShortcut.stored(nil), .controlCommandV)
        XCTAssertEqual(ClipboardShortcut.stored("x"), .controlCommandV)
        XCTAssertEqual(ClipboardShortcut.stored("⌃⌥⌘V"), .controlOptionCommandV)
        XCTAssertEqual(ClipboardShortcut.allCases.filter { $0.conflictWarning != nil }, [.shiftCommandV])
        XCTAssertEqual(ClipboardShortcut.controlCommandV.keyCode, 9)
    }

    func testCopiedWebImageWithOnlyHTMLIsAnImage() {
        XCTAssertEqual(ClipboardHistory.kind(of: [.png: Data(count: 8), .html: text("<img src=x>")]), .image)
    }
}
