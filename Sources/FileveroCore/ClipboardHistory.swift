import CryptoKit
import Foundation

public enum ClipboardFormat: String, Codable, CaseIterable, Sendable {
    case plainText, rtf, html, png, fileURLs
}

public enum ClipboardKind: String, Codable, Sendable {
    case file, image, link, richText, text
}

/// One read of the clipboard. `fileURLs` holds newline-separated paths as UTF-8. `pendingTIFF` is an image that
/// still has to become the PNG format; `ClipboardPasteboardCodec.storable` converts it.
public struct ClipboardCapture: Sendable {
    public var formats: [ClipboardFormat: Data]
    public var sourceApp: String?
    public var markers: Set<String>
    public var pendingTIFF: Data?

    public init(formats: [ClipboardFormat: Data], sourceApp: String?, markers: Set<String>, pendingTIFF: Data? = nil) {
        self.formats = formats
        self.sourceApp = sourceApp
        self.markers = markers
        self.pendingTIFF = pendingTIFF
    }
}

public struct ClipboardEntry: Codable, Equatable, Identifiable, Sendable {
    public var id: UUID
    public var created: Date
    public var pinned: Bool
    public var sourceApp: String?
    public var kind: ClipboardKind
    public var preview: String
    public var formats: [ClipboardFormat]
    public var digest: String

    public init(
        id: UUID, created: Date, pinned: Bool, sourceApp: String?, kind: ClipboardKind, preview: String,
        formats: [ClipboardFormat], digest: String
    ) {
        self.id = id
        self.created = created
        self.pinned = pinned
        self.sourceApp = sourceApp
        self.kind = kind
        self.preview = preview
        self.formats = formats
        self.digest = digest
    }

    public init(capture formats: [ClipboardFormat: Data], sourceApp: String?, at date: Date = Date()) {
        let kind = ClipboardHistory.kind(of: formats)
        self.init(
            id: UUID(), created: date, pinned: false, sourceApp: sourceApp, kind: kind,
            preview: ClipboardHistory.preview(of: formats, kind: kind),
            formats: ClipboardFormat.allCases.filter { formats[$0] != nil },
            digest: ClipboardHistory.digest(of: formats))
    }
}

/// Newest first. Every change returns a new history; the store removes blobs of entries that are gone.
public struct ClipboardHistory: Codable, Equatable, Sendable {
    public var entries: [ClipboardEntry]
    public var bootTime: Date?

    public init(entries: [ClipboardEntry] = [], bootTime: Date? = nil) {
        self.entries = entries
        self.bootTime = bootTime
    }

    public static let maxItemBytes = 10_485_760
    public static let restoreMarker = "app.filevero.clipboard-restore"
    // nspasteboard.org markers that password managers and generators set on content that must not be kept.
    public static let ignoredMarkers: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
        restoreMarker,
    ]
    public static let defaultExcludedApps = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop", "org.keepassxc.keepassxc",
        "com.apple.keychainaccess", "com.apple.Passwords",
    ]

    public static func shouldRecord(_ capture: ClipboardCapture, excludedApps: Set<String>) -> Bool {
        guard capture.markers.isDisjoint(with: ignoredMarkers), !capture.formats.isEmpty else { return false }
        return capture.sourceApp.map { !excludedApps.contains($0) } ?? true
    }

    public static func fitted(_ formats: [ClipboardFormat: Data]) -> [ClipboardFormat: Data]? {
        var kept = formats
        if kept.values.reduce(0, { $0 + $1.count }) > maxItemBytes { kept[.png] = nil }
        guard !kept.isEmpty, kept.values.reduce(0, { $0 + $1.count }) <= maxItemBytes else { return nil }
        return kept
    }

    public static func kind(of formats: [ClipboardFormat: Data]) -> ClipboardKind {
        if formats[.fileURLs] != nil { return .file }
        let text = plainText(formats)
        // Browsers put an <img> tag next to a copied image; that HTML is not a text counterpart.
        if formats[.png] != nil, text == nil, formats[.rtf] == nil { return .image }
        if let text, link(in: text) != nil { return .link }
        if formats[.rtf] != nil || formats[.html] != nil { return .richText }
        return .text
    }

    public static func link(in text: String) -> URL? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed),
              ["http", "https"].contains(url.scheme?.lowercased() ?? ""),
              url.host?.isEmpty == false
        else { return nil }
        return url
    }

    public static func digest(of formats: [ClipboardFormat: Data]) -> String {
        var hash = SHA256()
        for format in formats.keys.sorted(by: { $0.rawValue < $1.rawValue }) {
            let data = formats[format] ?? Data()
            hash.update(data: Data("\(format.rawValue):\(data.count):".utf8))
            hash.update(data: data)
        }
        return hash.finalize().map { String(format: "%02x", $0) }.joined()
    }

    public static func preview(of formats: [ClipboardFormat: Data], kind: ClipboardKind) -> String {
        switch kind {
        case .image:
            return ""
        case .file:
            let paths = filePaths(formats)
            let name = paths.first.map { URL(fileURLWithPath: $0).lastPathComponent } ?? ""
            return paths.count > 1 ? "\(name) +\(paths.count - 1)" : name
        case .link, .richText, .text:
            let line = plainText(formats)?.split(whereSeparator: \.isNewline)
                .map { $0.trimmingCharacters(in: .whitespaces) }
                .first { !$0.isEmpty } ?? ""
            return String(line.prefix(200))
        }
    }

    public static func plainText(_ formats: [ClipboardFormat: Data]) -> String? {
        formats[.plainText].flatMap { String(data: $0, encoding: .utf8) }.flatMap { $0.isEmpty ? nil : $0 }
    }

    public static func filePaths(_ formats: [ClipboardFormat: Data]) -> [String] {
        formats[.fileURLs].flatMap { String(data: $0, encoding: .utf8) }?
            .split(separator: "\n").map(String.init) ?? []
    }

    public func inserting(_ entry: ClipboardEntry, limit: Int) -> ClipboardHistory {
        var added = entry
        var rest = entries
        if let index = rest.firstIndex(where: { $0.digest == entry.digest }) {
            added.id = rest[index].id
            added.pinned = rest[index].pinned
            rest.remove(at: index)
        }
        return ClipboardHistory(entries: [added] + rest, bootTime: bootTime).trimmed(toLimit: limit)
    }

    /// Pinned entries do not count toward the limit and are never dropped.
    public func trimmed(toLimit limit: Int) -> ClipboardHistory {
        var result = entries
        while result.filter({ !$0.pinned }).count > limit, let oldest = result.lastIndex(where: { !$0.pinned }) {
            result.remove(at: oldest)
        }
        return ClipboardHistory(entries: result, bootTime: bootTime)
    }

    public func togglingPin(_ id: UUID) -> ClipboardHistory {
        ClipboardHistory(
            entries: entries.map { entry in
                guard entry.id == id else { return entry }
                var changed = entry
                changed.pinned.toggle()
                return changed
            }, bootTime: bootTime)
    }

    public func touching(_ id: UUID, at date: Date) -> ClipboardHistory {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return self }
        var moved = entries[index]
        moved.created = date
        var rest = entries
        rest.remove(at: index)
        return ClipboardHistory(entries: [moved] + rest, bootTime: bootTime)
    }

    public func removing(_ id: UUID) -> ClipboardHistory {
        ClipboardHistory(entries: entries.filter { $0.id != id }, bootTime: bootTime)
    }

    public func removingUnpinned() -> ClipboardHistory {
        ClipboardHistory(entries: entries.filter(\.pinned), bootTime: bootTime)
    }

    public func removingAll() -> ClipboardHistory {
        ClipboardHistory(entries: [], bootTime: bootTime)
    }

    public func afterBoot(_ boot: Date, clearOnRestart: Bool) -> ClipboardHistory {
        let restarted = bootTime != nil && bootTime != boot
        let kept = restarted && clearOnRestart ? entries.filter(\.pinned) : entries
        return ClipboardHistory(entries: kept, bootTime: boot)
    }
}
